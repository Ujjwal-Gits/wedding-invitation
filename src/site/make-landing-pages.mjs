// Writes, from the data (src/site/landings.mjs, seo.mjs, intl-content.mjs, content.mjs):
//   - one small page per landing page at its path (<path>/index.html); the partials fill the body at build
//   - public/sitemap.xml: every public page of both sites, with lastmod and image entries
//   - public/llms.txt (a short guide for AI engines) and public/llms-full.txt (every page's words in plain text)
// Run after changing a landing page, a slug or any page copy:  node src/site/make-landing-pages.mjs
// (designs/<slug>/ pages come from make-design-pages.mjs; run that first after adding a design.)
import { readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import { LANDINGS } from './landings.mjs';
import './partials.mjs'; // first: partials.mjs and landing.mjs import each other, and partials must be the one that starts
import { landingText } from './landing.mjs';
import { pageMeta, checkLengths, PAGES, LEGAL } from './seo.mjs';
import { INTL_PAGES, FAQ_SETS, faqList, fillUsd, EVENTS } from './intl-content.mjs';
import { faqItems, OCCASIONS, SITE_URL } from './content.mjs';
import { THEMES, FALLBACK_SITE, TIER_LABEL } from './themes.js';
import { phoneStill } from './stills.js';
import { intlPlans, usdText } from './intl-plans.js';
import { artSrc, STYLE_LABEL, INTL_THEMES, INTL_BY_SLUG } from './intl-designs.js';
import { TRUST_PAGES } from './seo-site.mjs';
import { renderPartials } from './partials.mjs';
import { lastmodOf, saveLastmods, sourceOf, writeSitemap, writeSitemapIndex } from './sitemaps.mjs';

const ROOT = resolve(import.meta.dirname, '..', '..');
const stills = JSON.parse(readFileSync(resolve(import.meta.dirname, 'stills.json'), 'utf8'));
const thumbs = new Set(JSON.parse(readFileSync(resolve(import.meta.dirname, 'thumbs.json'), 'utf8')));
const still = (slug) => phoneStill(stills, slug, thumbs.has(slug) ? `/site/thumbs/${slug}-480.webp` : `/themes/${slug}/thumb.jpg`);
// { np: [slug], intl: [slug] }: the design pages make-design-pages.mjs wrote (/designs/<slug>/, /international/designs/<slug>/)
const designPages = JSON.parse(readFileSync(resolve(import.meta.dirname, 'design-pages.json'), 'utf8'));

const warn = checkLengths();
if (warn.length) { console.error(`seo: fix these first:\n${warn.join('\n')}`); process.exit(1); }

/* ---------------- the pages ---------------- */
const MANIFEST = resolve(import.meta.dirname, 'landing-pages.json');
const before = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : [];
const heroImg = (l) => (l.hero?.design ? still(l.hero.design).src : l.hero?.art ? artSrc(l.hero.art, 800) : null);
function shell(id, l) {
  const intl = l.market === 'intl';
  const pre = l.hero?.design ? still(l.hero.design) : null;
  const preload = pre ? `\n  <link rel="preload" as="image" href="${pre.src}"${pre.srcset ? ` imagesrcset="${pre.srcset}" imagesizes="(max-width: 899px) 58vw, 300px"` : ''} fetchpriority="high" />`
    : l.hero?.art ? `\n  <link rel="preload" as="image" href="${artSrc(l.hero.art, 800)}" imagesrcset="${artSrc(l.hero.art, 480)} 480w, ${artSrc(l.hero.art, 800)} 800w, ${artSrc(l.hero.art, 1170)} 1170w" imagesizes="(max-width: 899px) 58vw, 300px" fetchpriority="high" />` : '';
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
  <!-- Generated by src/site/make-landing-pages.mjs from src/site/landings.mjs. Edit those, not this file. -->${preload}
  <!--@head:land/${id}-->
  <!--@land-ld:${id}-->
  <script type="module" src="/src/site/${intl ? 'intl' : 'site'}.js"></script>
</head>
<body data-page="landing"${intl ? ' class="market-intl"' : ''}${l.catalog ? ` data-catalog="${l.catalog}"` : ''}>
  ${intl ? `<!--@intl-header:land/${id}-->` : `<!--@header:${l.parent === 'occasions' ? 'occasions' : ''}-->`}
  <main id="main"><!--@landing:${id}--></main>
  ${intl ? '<!--@intl-footer-->' : '<!--@footer-->'}
  ${intl ? '<!--@dialogs:intl-->' : '<!--@dialogs-->'}
</body>
</html>
`;
}
const written = [];
for (const [id, l] of Object.entries(LANDINGS)) {
  const dir = resolve(ROOT, `.${l.path}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, 'index.html'), shell(id, l));
  written.push(l.path);
}
// a slug that changed: remove the old generated page (only pages this script made)
for (const p of before) {
  if (written.includes(p)) continue;
  const f = resolve(ROOT, `.${p}`, 'index.html');
  if (existsSync(f) && readFileSync(f, 'utf8').includes('make-landing-pages.mjs')) { rmSync(f); console.log(`removed old landing page ${p}`); }
}
writeFileSync(MANIFEST, `${JSON.stringify(written, null, 1)}\n`);

/* ---------------- the sitemaps (src/site/sitemaps.mjs): an index and one file per group ---------------- */
// <lastmod> is the date each page's own content last changed (lastmod.json); private pages (/studio/, /pay/ ...) and
// the gated design pages (/<theme>/) are never listed. The blog adds sitemap-blog.xml itself.
const today = new Date().toISOString().slice(0, 10);
const groups = { 'sitemap-pages-np.xml': [], 'sitemap-pages-intl.xml': [], 'sitemap-designs.xml': [] };
const images = [];
const keep = new Set();
const add = (file, path, imgs = [], sources = []) => {
  if (keep.has(path)) return;
  const shell = existsSync(sourceOf(path)) ? readFileSync(sourceOf(path), 'utf8') : '';
  if (/<meta name="robots" content="[^"]*noindex/i.test(shell)) return; // never list a noindex page
  keep.add(path);
  const lastmod = lastmodOf(path, renderPartials, { sources });
  groups[file].push({ path, lastmod });
  const list = imgs.filter(Boolean);
  if (list.length) images.push({ path, lastmod, imgs: list });
};
const NP = 'sitemap-pages-np.xml', INTL = 'sitemap-pages-intl.xml', DESIGNS = 'sitemap-designs.xml';
for (const id of Object.keys(PAGES)) add(NP, PAGES[id].path, id === 'designs' ? THEMES.slice(0, 12).map((t) => still(t.slug).src) : [], ['src/site/content.mjs']);
for (const [id, m] of Object.entries(TRUST_PAGES)) add(m.market === 'intl' ? INTL : NP, m.path, [], ['src/site/trust.mjs']);
for (const [id, l] of Object.entries(LANDINGS)) if (l.market !== 'intl') add(NP, l.path, [heroImg(l), ...(Array.isArray(l.designs?.list) ? l.designs.list.map((s) => still(s).src) : [])], ['src/site/landings.mjs']);
for (const id of Object.keys(LEGAL)) add(NP, LEGAL[id].path);
for (const id of Object.keys(INTL_PAGES)) add(INTL, INTL_PAGES[id].path, id === 'intl/designs' || id === 'intl/home' ? INTL_THEMES.map((d) => still(d.slug).src) : [], ['src/site/intl-content.mjs']);
for (const [id, l] of Object.entries(LANDINGS)) if (l.market === 'intl') add(INTL, l.path, [heroImg(l), ...(Array.isArray(l.designs?.list) ? l.designs.list.map((s) => still(s).src) : [])], ['src/site/landings.mjs']);
for (const s of designPages.np) add(DESIGNS, `/designs/${s}/`, [still(s).src]);
for (const s of designPages.intl) add(DESIGNS, `/international/designs/${s}/`, [still(s).src]);
for (const [file, entries] of Object.entries(groups)) writeSitemap(file, entries);
writeSitemap('sitemap-images.xml', images, { images: true });
saveLastmods(keep);
const indexed = writeSitemapIndex();
const urls = [...keep];

/* ---------------- llms.txt and llms-full.txt ---------------- */
const strip = (s) => String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&');
const npPlans = FALLBACK_SITE.plans;
const iPlans = intlPlans(FALLBACK_SITE.plans);
const rs = (n) => `Rs ${new Intl.NumberFormat('en-IN').format(n)}`;
const line = (id) => { const m = pageMeta(id); return `- [${m.title.replace(/ \| Nimtto$/, '')}](${m.url}): ${m.desc}`; };
const npIds = [...Object.keys(PAGES).filter((k) => k !== 'credits'), 'about', ...Object.keys(LANDINGS).filter((k) => LANDINGS[k].market === 'np').map((k) => `land/${k}`)];
const iIds = [...Object.keys(INTL_PAGES), 'intl/about', ...Object.keys(LANDINGS).filter((k) => LANDINGS[k].market === 'intl').map((k) => `land/${k}`)];
const facts = `## Key facts
- Website: ${SITE_URL} (Nepal, prices in rupees) and ${SITE_URL}/international/ (worldwide, prices in US dollars)
- What it is: an animated invitation that opens like a real card, with an event website (schedule, maps, travel notes, story, photos, music) and RSVP, shared as one link. A real designer sets it up with the customer; guests need no app or account.
- Based in: Nepal. Works online with families in Nepal and couples and hosts worldwide.
- Contact: email nimttoz@gmail.com, WhatsApp +977 980-6393298 (English and Nepali). Replies usually within one business day.
- Payment: one payment, no subscription, no charge per guest. Nepal: Khalti, eSewa or bank QR (Fonepay), confirmed by hand. Abroad: card or PayPal in US dollars; the plan switches on as soon as the payment goes through.
- Delivery: the invitation appears in the customer's dashboard as soon as payment is confirmed; design help usually takes 1 to 3 business days. Invitations stay online for at least one year after the event date.
- Custom designs: an enquiry. Nimtto replies within one business day with a price.
- Refunds: payments are final; in a critical case a customer can ask, and Nimtto may approve a full or partial refund; problems with an invitation are fixed free. Terms: ${SITE_URL}/terms/ · Privacy: ${SITE_URL}/privacy/ · Refunds: ${SITE_URL}/refunds/

## Prices
Nepal (${SITE_URL}/pricing/): ${npPlans.map((p) => `${p.name} ${p.from ? 'from ' : ''}${rs(p.price)}`).join('; ')}.
International (${SITE_URL}/international/pricing/): ${iPlans.map((p) => `${p.name} ${p.from ? 'from ' : ''}${usdText(p.usd)}`).join('; ')}.
Plans: ${npPlans.filter((p) => p.id !== 'custom').map((p) => `${p.name}: ${p.features.join(', ')}`).join('. ')}.
`;
const llms = `# Nimtto

> Nimtto (निम्तो, "invitation" in Nepali) makes animated invitation websites with RSVP, set up with you by a real designer. Two sites: nimtto.com for Nepali weddings and family ceremonies in Nepal (English and Nepali, Bikram Sambat dates, rupees, Khalti/eSewa/QR), and nimtto.com/international/ for weddings and every celebration worldwide (US dollars, card or PayPal), including Nepali and South Asian weddings abroad.

${facts}
## Nepal site
${npIds.map(line).join('\n')}

## International site
${iIds.map(line).join('\n')}

## International designs
${designPages.intl.map((s) => line(`intl-design/${s}`)).join('\n')}

## Policies
${Object.keys(LEGAL).map(line).join('\n')}

## More
- Every page's words in plain text: ${SITE_URL}/llms-full.txt
- Sitemap: ${SITE_URL}/sitemap.xml
`;
writeFileSync(resolve(ROOT, 'public', 'llms.txt'), llms);

const qa = (items) => items.map((x) => `### ${strip(x.q)}\n${strip(x.a)}\n`).join('\n');
const sections = [];
const npFaqSet = { home: 'home', designs: 'designs', occasions: 'occasions', 'how-it-works': 'how', features: 'features', pricing: 'pricing', contact: 'contact', faq: 'faq' };
for (const id of Object.keys(PAGES).filter((k) => k !== 'credits')) {
  const m = pageMeta(id);
  sections.push(`## ${m.title}\nURL: ${m.url}\n${m.desc}\n\n${npFaqSet[id] ? qa(faqItems(npFaqSet[id])) : ''}`);
}
const intlFaqSet = { 'intl/home': 'home', 'intl/designs': 'designs', 'intl/occasions': 'occasions', 'intl/features': 'features', 'intl/how': 'how', 'intl/pricing': 'pricing', 'intl/faq': 'faq', 'intl/contact': 'contact' };
for (const id of Object.keys(INTL_PAGES)) {
  const m = pageMeta(id);
  const p = INTL_PAGES[id];
  const set = FAQ_SETS[intlFaqSet[id]];
  const keys = Array.isArray(set?.[0]) ? set.flatMap(([, k]) => k) : set || [];
  sections.push(`## ${m.title}\nURL: ${m.url}\n${strip(p.h1)}. ${fillUsd(p.lede)}\n\n${qa(faqList(keys))}`);
}
for (const id of Object.keys(LANDINGS)) {
  const m = pageMeta(`land/${id}`);
  // the page's own words, with its guide sections one level down (## -> ###)
  sections.push(`## ${m.title}\nURL: ${m.url}\n${m.desc}\n\n${landingText(id).replace(/^### /gm, '#### ').replace(/^## /gm, '### ')}\n`);
}
const designsText = `## Designs
Nepal site (${THEMES.length} wedding designs; the lowest plan that includes each):
${['saral', 'shubha', 'shahi'].map((t) => `- ${TIER_LABEL[t]}: ${THEMES.filter((x) => x.tier === t).map((x) => `${x.name} (${x.ne}): ${x.concept}`).join('; ')}`).join('\n')}
International site (animated wedding designs, by style; each has its own page):
${designPages.intl.map((s) => INTL_BY_SLUG[s]).filter(Boolean).map((d) => `- ${d.name} (${STYLE_LABEL[d.style]}, from ${usdText(iPlans.find((p) => p.id === d.tier)?.usd ?? 49)}): ${d.line} ${SITE_URL}/international/designs/${d.slug}/`).join('\n')}
Occasions designed on the Custom plan: Nepal: ${OCCASIONS.filter((o) => !o.designs).map((o) => o.en).join(', ')}. International: ${EVENTS.filter((o) => !o.lead).map((o) => o.en).join(', ')}.
`;
writeFileSync(resolve(ROOT, 'public', 'llms-full.txt'), `# Nimtto: the full text\n\n> Every public page of nimtto.com (Nepal) and nimtto.com/international/ (worldwide), in plain text for AI engines. Updated ${today}.\n\n${facts}\n${designsText}\n${sections.join('\n')}`);

console.log(`landing pages: ${written.length}; sitemaps: ${urls.length} urls in ${indexed.join(', ')}; llms.txt and llms-full.txt written`);
